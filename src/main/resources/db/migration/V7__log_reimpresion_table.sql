-- V7__log_reimpresion_table.sql
-- Tabla inmutable de auditoría para registro de reimpresión de tickets (HU-22.01 / Notion: CA-03)

CREATE TABLE IF NOT EXISTS log_reimpresion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id UUID NOT NULL REFERENCES tickets(uuid_codigo),
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    motivo VARCHAR(500) NOT NULL,
    fecha_reimpresion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_log_reimpresion_ticket ON log_reimpresion (ticket_id);
CREATE INDEX IF NOT EXISTS idx_log_reimpresion_usuario ON log_reimpresion (usuario_id);
CREATE INDEX IF NOT EXISTS idx_log_reimpresion_fecha ON log_reimpresion (fecha_reimpresion DESC);
